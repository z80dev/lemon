import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { TUI_KEYBINDINGS } from "@oh-my-pi/pi-tui/keybindings";
import { createCommandRegistry, type SlashCommand } from "../src/commands/index.ts";

import { LEMON_KEYBINDINGS } from "../src/ui/controllers/input-controller.ts";

const target = new URL("../../../docs/user-guide/tui-commands.md", import.meta.url);

export function cell(value: string): string {
	return value
		.replaceAll("&", "&amp;")
		.replaceAll("<", "&lt;")
		.replaceAll(">", "&gt;")
		.replaceAll("|", "&#124;")
		.replaceAll("`", "&#96;")
		.replace(/\r?\n/g, " ");
}

export async function renderCommandsDoc(): Promise<string> {
	const commands = createCommandRegistry().list();
	const index = new URL("../src/commands/index.ts", import.meta.url);
	const source = await readFile(index, "utf8");
	const modules = [
		...new Set([...source.matchAll(/from "(\.\/[^"\n]+\.ts)"/g)].map((match) => match[1])),
	].sort();
	const owners = new Map<string, string>();
	for (const path of modules) {
		const exports = await import(new URL(path, index).href);
		for (const value of Object.values(exports)) {
			if (value && typeof value === "object" && "name" in value && "run" in value) {
				owners.set((value as SlashCommand).name, path.slice(2, -3));
			}
		}
		// The editor command is the registry's only command factory; constructing
		// its metadata never invokes the external-editor callback.
		if (exports.makeEditorCommand)
			owners.set(exports.makeEditorCommand(async () => {}).name, path.slice(2, -3));
	}
	const groups = new Map<string, SlashCommand[]>();
	for (const command of commands) {
		const owner = owners.get(command.name);
		if (!owner) throw new Error(`No source module for /${command.name}`);
		const group = groups.get(owner) ?? [];
		group.push(command);
		groups.set(owner, group);
	}
	const lines = [
		"# TUI slash commands",
		"",
		"<!-- Generated by clients/tui/scripts/generate-commands-doc.ts; do not edit. -->",
		"",
		"Built-in terminal commands, grouped by source module. Type `/help <command>`",
		"in the TUI for live availability; some commands require daemon methods or UI hooks.",
		"Aliases accept the same arguments as their command. `—` means no arguments or aliases.",
		"",
		"Project-defined prompt commands are covered in [file slash commands](slash-commands.md).",
		"See the [TUI guide](../../clients/tui/README.md) for keyboard shortcuts and client setup.",
		"",
		"Regenerate from the repository root with `bun clients/tui/scripts/generate-commands-doc.ts`.",
		"",
	];
	for (const [module, entries] of [...groups].sort(([a], [b]) => a.localeCompare(b))) {
		lines.push(
			`## ${module}`,
			"",
			"| Command | Aliases | Arguments | Description |",
			"| --- | --- | --- | --- |",
		);
		for (const command of entries) {
			lines.push(
				`| /${cell(command.name)} | ${cell(command.aliases?.map((alias) => `/${alias}`).join(", ") || "—")} | ${cell(command.usage || "—")} | ${cell(command.summary)} |`,
			);
		}
		lines.push("");
	}
	lines.push(
		"## Prompt history",
		"",
		"The ↑ / ↓ prompt recall persists across sessions in",
		"`~/.lemon/tui-history/history.sqlite3` (SQLite, mode `0600`, private `0700` directory).",
		"Transactions retain at most 100 prompts and 256 KiB of encoded prompt content;",
		"SQLite pages and its temporary rollback journal need additional disk space.",
		"",
		"- `/clear-history` forgets remembered prompts, clears saved rows and removes legacy sources.",
		"- Set `prompt_history = false` under `[tui]` in user or project config to stop",
		"  saving and loading history. Existing history remains until `/clear-history`.",
		"",
		"Only submitted prompts are saved; discarded drafts stay in memory for this session.",
		"Prompts may contain secrets. See [TUI prompt history](../config.md#tui-prompt-history)",
		"for storage bounds, migration, concurrent clear semantics and backup considerations.",
		"",
	);
	lines.push(
		"## Configurable keybindings",
		"",
		"Set quoted action IDs under `[tui.keys]` in `~/.lemon/config.toml` or the project",
		"`.lemon/config.toml`. Values replace the defaults: a key string, an array of keys,",
		'or `[]` / `"none"` to unbind. See [TUI configuration](../config.md#tui-keybindings).',
		"Overlays own their keys; picker-local shortcuts are not configurable here.",
		"",
		"| Action ID | Default keys | Description |",
		"| --- | --- | --- |",
	);
	for (const [id, binding] of Object.entries({ ...LEMON_KEYBINDINGS, ...TUI_KEYBINDINGS })) {
		const keys = [binding.defaultKeys].flat().join(", ") || "unbound";
		lines.push(`| ${cell(id)} | ${cell(keys)} | ${cell(binding.description)} |`);
	}
	lines.push("");
	return lines.join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
	const expected = await renderCommandsDoc();
	if (process.argv.includes("--check")) {
		const current = await readFile(target, "utf8").catch((error: NodeJS.ErrnoException) => {
			if (error.code === "ENOENT") return "";
			throw error;
		});
		if (current !== expected) {
			console.error("Stale TUI command docs: run bun clients/tui/scripts/generate-commands-doc.ts");
			process.exitCode = 1;
		} else console.log("TUI command docs are current");
	} else await writeFile(target, expected);
}
