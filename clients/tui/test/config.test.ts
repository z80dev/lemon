/**
 * The TUI's config writes: single keys edited in place in the daemon's
 * config.toml, never a re-serialized file.
 */

import { afterEach, beforeEach, describe, expect, test } from "bun:test";
import { mkdirSync, mkdtempSync, readFileSync, rmSync, statSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import {
	loadConfig,
	parseDottedKey,
	saveDefaultModel,
	saveTheme,
	upsertTomlString,
} from "../src/config.ts";

let home: string;
let previousHome: string | undefined;

beforeEach(() => {
	previousHome = process.env.HOME;
	home = mkdtempSync(join(tmpdir(), "lemon-tui-config-"));
	process.env.HOME = home;
});

afterEach(() => {
	if (previousHome === undefined) delete process.env.HOME;
	else process.env.HOME = previousHome;
	rmSync(home, { recursive: true, force: true });
});

function configPath(): string {
	return join(home, ".lemon", "config.toml");
}

function writeConfig(content: string, mode = 0o600): void {
	mkdirSync(join(home, ".lemon"), { recursive: true });
	writeFileSync(configPath(), content, { mode });
}

/** What `lemon setup` writes for a ChatGPT (openai-codex) sign-in. */
const SETUP_WRITTEN = `# Lemon configuration
# Generated by lemon setup

[runtime]
theme = "default"

[gateway]
max_concurrent_runs = 2
auto_resume = false
enable_telegram = false

[tui]
theme = "lemon"

[providers.openai-codex]
oauth_secret = "llm_openai_codex_api_key"
auth_source = "oauth"

[defaults]
provider = "openai-codex"
model = "openai-codex:gpt-5.1"
`;

describe("saveDefaultModel", () => {
	test("edits [defaults] in place and keeps every other table and comment", async () => {
		writeConfig(SETUP_WRITTEN);
		await saveDefaultModel("openai", "openai:gpt-5.1");

		const written = readFileSync(configPath(), "utf-8");
		expect(written).toBe(
			SETUP_WRITTEN.replace(
				'provider = "openai-codex"\nmodel = "openai-codex:gpt-5.1"',
				'provider = "openai"\nmodel = "openai:gpt-5.1"',
			),
		);
		expect(written).not.toContain("[agent]");
		expect(written).not.toContain("[control_plane]");
		expect(statSync(configPath()).mode & 0o777).toBe(0o600);
	});

	test("adds [defaults] to a file without one and creates a missing file privately", async () => {
		await saveDefaultModel("anthropic", "anthropic:claude-sonnet-4");
		expect(readFileSync(configPath(), "utf-8")).toBe(
			'[defaults]\nprovider = "anthropic"\nmodel = "anthropic:claude-sonnet-4"\n',
		);
		expect(statSync(configPath()).mode & 0o777).toBe(0o600);
	});

	test("refuses to write when the edit would not parse", async () => {
		const broken = '[defaults]\nmodel = "x"\n\n[gateway]\nport = \n';
		writeConfig(broken);
		await expect(saveDefaultModel("openai", "openai:gpt-5")).rejects.toThrow(/would not parse/);
		expect(readFileSync(configPath(), "utf-8")).toBe(broken);
	});
});

describe("saveTheme and loadConfig", () => {
	test("reads notifications from the global TUI table", async () => {
		writeConfig('[tui]\nnotifications = "bell"\n');
		expect((await loadConfig()).tui?.notifications).toBe("bell");
	});

	test("round-trip through [tui] theme", async () => {
		writeConfig(SETUP_WRITTEN);
		await saveTheme("dark");
		expect(readFileSync(configPath(), "utf-8")).toBe(
			SETUP_WRITTEN.replace('theme = "lemon"', 'theme = "dark"'),
		);
		expect((await loadConfig()).tui?.theme).toBe("dark");
		expect((await loadConfig()).defaults?.model).toBe("openai-codex:gpt-5.1");
	});

	test("project config overlays the global one", async () => {
		writeConfig('[tui]\ntheme = "light"\n');
		const project = mkdtempSync(join(tmpdir(), "lemon-tui-project-"));
		try {
			mkdirSync(join(project, ".lemon"));
			writeFileSync(join(project, ".lemon", "config.toml"), '[tui]\ntheme = "dark"\n');
			expect((await loadConfig(project)).tui?.theme).toBe("dark");
		} finally {
			rmSync(project, { recursive: true, force: true });
		}
	});
});

describe("upsertTomlString", () => {
	test("matches quoted table headers instead of appending a duplicate", () => {
		const content = '[providers."openai-codex"]\nauth_source = "oauth"\n';
		const patched = upsertTomlString(content, "providers.openai-codex", "oauth_secret", "s");
		expect(patched).toBe('[providers."openai-codex"]\nauth_source = "oauth"\noauth_secret = "s"\n');
	});

	test("puts a missing parent table in front of its first child", () => {
		const patched = upsertTomlString('[tui.colors]\naccent = "x"\n', "tui", "theme", "dark");
		expect(patched).toBe('[tui]\ntheme = "dark"\n\n[tui.colors]\naccent = "x"\n');
		expect(Bun.TOML.parse(patched)).toEqual({ tui: { theme: "dark", colors: { accent: "x" } } });
	});

	test("escapes values as TOML basic strings", () => {
		const patched = upsertTomlString("", "tui", "theme", 'a"b\\c');
		expect(Bun.TOML.parse(patched)).toEqual({ tui: { theme: 'a"b\\c' } });
	});

	test("parses dotted keys", () => {
		expect(parseDottedKey('providers . "openai-codex"')).toEqual(["providers", "openai-codex"]);
		expect(parseDottedKey("a.'b.c'")).toEqual(["a", "b.c"]);
		expect(parseDottedKey("a..b")).toBeUndefined();
	});
});
