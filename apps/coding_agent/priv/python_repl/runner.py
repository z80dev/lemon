#!/usr/bin/env python3
"""Lemon persistent python kernel runner (protocol v1).

The parent (an Erlang port owner) spawns this script with the resolved
interpreter, unbuffered, from a private ``0700`` workspace that also holds
``lemon_tools.py``. All protocol travels over the *original* stdout
descriptor, which is duplicated early into a non-inheritable control fd; fd 1
and fd 2 are then re-pointed at capture pipes so user stdout/stderr — however
produced — can never be mistaken for control frames. Protocol is therefore
typed and request-correlated, and the model-facing output contract stays
"only what the script prints".

Parent requests arrive as UTF-8 NDJSON on stdin:

    {"v":1,"type":"init","cwd":"/canonical/path"}
    {"v":1,"type":"eval","id":"cell-id","code":"...","cwd":"...","bridge":{...}}
    {"v":1,"type":"shutdown"}

Every emitted frame is ``RS + b"lemon-python\\t" + JSON + newline`` on the
control fd: ``ready`` (answers ``init``), ``started``/``stream``/``exception``
/``done`` (one ``done`` per ``started``), ``fatal`` (malformed request; the
process then exits non-zero), and ``bye`` (answers ``shutdown``; exit 0).
Stream payloads are base64 of at most 64 KiB of raw bytes. The host rejects
frames over 256 KiB, so chunking stays well inside that budget.

Semantics per the plan:

- exactly one globals namespace for the process lifetime; ordinary
  exceptions, ``SystemExit``, and rejected ``input()`` keep it,
- ``input()``/stdin reads raise an explicit unsupported-input error,
- the keyed cwd is restored before every cell,
- tracebacks are filtered of runner frames,
- code that already produced ``started`` is never replayed by this process,
- a POSIX session/process group is started when safe, and descendants never
  inherit the control fd (they do inherit the captured fd 1/2 on purpose).

Only the python3 standard library is used.
"""

import base64
import builtins
import importlib
import inspect
import io
import json
import os
import select
import sys
import threading
import time
import traceback

PROTOCOL_VERSION = 1
FRAME_PREFIX = b"\x1elemon-python\t"
CELL_FILENAME = "<cell>"

# Stream frames carry base64 of at most STREAM_CHUNK raw bytes, keeping every
# frame far below the host-side 256 KiB cap.
STREAM_CHUNK = 64 * 1024

# Exception frames must remain materially smaller than the host's 256 KiB
# frame cap even when exception classes, messages, or traceback details are
# hostile. These limits include JSON string escaping and leave substantial
# headroom for frame metadata and the control prefix.
EXCEPTION_NAME_JSON_BYTES = 4 * 1024
EXCEPTION_MESSAGE_JSON_BYTES = 48 * 1024
EXCEPTION_TRACEBACK_JSON_BYTES = 80 * 1024
EXCEPTION_TRUNCATION_MARKER = "... [truncated]"

# After a cell's code returns, its pipes are declared drained once both have
# stayed quiet for QUIET_SECONDS (and no frame write is in flight), bounded by
# MAX_QUIESCE_SECONDS so a lingering user thread cannot stall the cell.
QUIET_SECONDS = 0.05
MAX_QUIESCE_SECONDS = 0.5

EXIT_OK = 0
EXIT_FATAL = 70
EXIT_CONTROL_LOST = 75

# Names copied from lemon_tools into the persistent namespace on bridged
# cells; mirrors the per-call import line generated by PythonShim.
HELPER_NAMES = (
    "ToolError",
    "read",
    "grep",
    "find",
    "ls",
    "webfetch",
    "text",
    "notify",
    "batch",
)


class ProtocolError(Exception):
    """A parent request violated the protocol; the kernel must die."""


class UnsupportedInput(RuntimeError):
    """Raised when cell code tries to read interactive input."""


_INPUT_ERROR = (
    "input() is not supported: the lemon persistent python kernel has no "
    "interactive stdin; read from a file or call a helper function instead"
)

_RUNNER_PATH = os.path.realpath(__file__)
_RUNNER_DIR = os.path.dirname(_RUNNER_PATH)

_write_lock = threading.Lock()
_cell_lock = threading.Lock()
_inflight_lock = threading.Lock()
_inflight_writes = 0
_open_cell = None
_drainers = []

_control_fd = None
_base_cwd = None
_namespace = {"__name__": "__main__", "__doc__": None, "__builtins__": builtins}


# ---------------------------------------------------------------------------
# frames
# ---------------------------------------------------------------------------


def _hard_exit(code):
    # The control channel is gone or unusable; nothing the interpreter does
    # from here can be observed, so do not run user atexit hooks.
    os._exit(code)


def _frame_data(payload):
    return FRAME_PREFIX + json.dumps(payload, separators=(",", ":")).encode("utf-8") + b"\n"


def _write_data(data):
    view = memoryview(data)
    while view:
        try:
            written = os.write(_control_fd, view)
        except OSError:
            _hard_exit(EXIT_CONTROL_LOST)
        view = view[written:]


def _write_frame(payload):
    with _write_lock:
        _write_data(_frame_data(payload))


def _write_stream_frame(cell_id, payload):
    """Write a stream frame only while its cell remains open.

    Closing a cell and writing its ``done`` frame share ``_write_lock`` with
    this check. Thus a stream either wins the lock and precedes ``done``, or
    loses it and is dropped after the cell is no longer attributable.
    """
    data = _frame_data(payload)
    with _write_lock:
        if _current_cell() != cell_id:
            return
        _write_data(data)


def _current_cell():
    with _cell_lock:
        return _open_cell


def _set_open_cell(cell_id):
    global _open_cell
    with _cell_lock:
        _open_cell = cell_id


def _begin_stream_write():
    """Atomically claim an open cell before a drainer emits for it."""
    global _inflight_writes
    with _cell_lock:
        cell_id = _open_cell
        if cell_id is None:
            return None
        with _inflight_lock:
            _inflight_writes += 1
        return cell_id


def _end_stream_write():
    global _inflight_writes
    with _inflight_lock:
        _inflight_writes -= 1


def _close_cell_and_emit_done(cell_id):
    """Remove attribution before the terminal frame, without reordering."""
    with _write_lock:
        _set_open_cell(None)
        _write_data(_frame_data({"v": PROTOCOL_VERSION, "type": "done", "id": cell_id}))


def _emit_stream(cell_id, stream_name, data):
    if cell_id is None:
        # Bytes from a user thread that outlived its cell are dropped: they
        # cannot be attributed to a live cell and must never touch the
        # control channel unframed.
        return
    for start in range(0, len(data), STREAM_CHUNK):
        chunk = data[start : start + STREAM_CHUNK]
        _write_stream_frame(
            cell_id,
            {
                "v": PROTOCOL_VERSION,
                "type": "stream",
                "id": cell_id,
                "stream": stream_name,
                "data": base64.b64encode(chunk).decode("ascii"),
            },
        )


