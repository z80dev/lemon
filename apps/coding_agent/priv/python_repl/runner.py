def _safe_str(value):
    try:
        return str(value)
    except Exception:
        return "<unprintable %s>" % type(value).__name__


def _unicode_scalar_safe_text(value):
    """Replace lone UTF-16 surrogates, which JSON decoders must reject."""
    if not any(0xD800 <= ord(char) <= 0xDFFF for char in value):
        return value

    return "".join(
        "\uFFFD" if 0xD800 <= ord(char) <= 0xDFFF else char for char in value
    )


def _json_escaped_character_size(char):
    """Return the byte count `json.dumps(char)` contributes inside quotes."""
    codepoint = ord(char)
    if char in ('"', "\\", "\b", "\f", "\n", "\r", "\t"):
        return 2
    if codepoint <= 0x1F:
        return 6
    if codepoint <= 0x7E:
        return 1
    if codepoint <= 0xFFFF:
        return 6
    return 12


def _bounded_exception_text(value, max_json_bytes):
    """Limit a JSON string without splitting Unicode or hiding truncation."""
    value = _unicode_scalar_safe_text(value)

    marker_bytes = sum(_json_escaped_character_size(char) for char in EXCEPTION_TRUNCATION_MARKER)
    content_limit = max_json_bytes - 2
    used = 0

    for index, char in enumerate(value):
        char_bytes = _json_escaped_character_size(char)
        if used + char_bytes > content_limit:
            prefix_limit = content_limit - marker_bytes
            prefix_used = 0
            prefix_end = 0

            for prefix_end, prefix_char in enumerate(value):
                prefix_char_bytes = _json_escaped_character_size(prefix_char)
                if prefix_used + prefix_char_bytes > prefix_limit:
                    break
                prefix_used += prefix_char_bytes
            else:
                prefix_end = len(value)

            return value[:prefix_end] + EXCEPTION_TRUNCATION_MARKER
        used += char_bytes

    return value


def _is_runner_frame(filename):
    try:
        return os.path.realpath(filename) == _RUNNER_PATH
    except (OSError, TypeError):
        return False


def _format_traceback(exc, name, message, unbounded_message):
    """Format a bounded user traceback without runner frames."""
    entries = []
    tb = exc.__traceback__
    while tb is not None:
        code = tb.tb_frame.f_code
        if not _is_runner_frame(code.co_filename):
            entries.append(
                (
                    _bounded_exception_text(code.co_filename, EXCEPTION_NAME_JSON_BYTES),
                    tb.tb_lineno,
                    _bounded_exception_text(code.co_name, EXCEPTION_NAME_JSON_BYTES),
                    None,
                )
            )
        tb = tb.tb_next

    lines = []
    if entries:
        lines.append("Traceback (most recent call last):\n")
        lines.extend(traceback.format_list(entries))
    if name == type(exc).__name__ and message == unbounded_message:
        lines.extend(traceback.format_exception_only(type(exc), exc))
    else:
        lines.append("%s: %s" % (name, message))
    return "".join(lines).rstrip("\n")


def _safe_format_traceback(exc, name, message, unbounded_message):
    try:
        traceback_text = _format_traceback(exc, name, message, unbounded_message)
    except Exception:
        traceback_text = "%s: <unformattable exception>" % name
    return _bounded_exception_text(traceback_text, EXCEPTION_TRACEBACK_JSON_BYTES)


def _exception_kind(exc):
    if isinstance(exc, UnsupportedInput):
        return "unsupported_input"
    if isinstance(exc, SystemExit):
        return "system_exit"
    if isinstance(exc, KeyboardInterrupt):
        return "interrupted"
    return "error"


def _system_exit_message(exc):
    if exc.code is None:
        return "SystemExit"
    if isinstance(exc.code, bool):
        return "SystemExit: %s" % exc.code
    if isinstance(exc.code, int):
        return "SystemExit: %d" % exc.code
    return "SystemExit: %s" % _safe_str(exc.code)


def _emit_exception(cell_id, exc):
    name = _bounded_exception_text(type(exc).__name__, EXCEPTION_NAME_JSON_BYTES)
    if isinstance(exc, SystemExit):
        unbounded_message = _system_exit_message(exc)
    else:
        unbounded_message = _safe_str(exc)
    message = _bounded_exception_text(unbounded_message, EXCEPTION_MESSAGE_JSON_BYTES)
    _write_frame(
        {
            "v": PROTOCOL_VERSION,
            "type": "exception",
            "id": cell_id,
            "kind": _exception_kind(exc),
            "name": name,
            "message": message,
            "traceback": _safe_format_traceback(exc, name, message, unbounded_message),
        }
    )


