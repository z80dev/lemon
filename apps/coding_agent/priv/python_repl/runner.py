def _parse_request(line):
    try:
        request = json.loads(line)
    except ValueError:
        raise ProtocolError("request is not valid JSON")
    if not isinstance(request, dict):
        raise ProtocolError("request is not a JSON object")
    if request.get("v") != PROTOCOL_VERSION:
        raise ProtocolError("unsupported protocol version")
    kind = request.get("type")
    if kind == "init":
        if not isinstance(request.get("cwd"), str) or not request["cwd"]:
            raise ProtocolError("init requires a cwd string")
    elif kind == "eval":
        if not isinstance(request.get("id"), str) or not request["id"]:
            raise ProtocolError("eval requires an id string")
        if not isinstance(request.get("code"), str):
            raise ProtocolError("eval requires a code string")
        cwd = request.get("cwd")
        if cwd is not None and (not isinstance(cwd, str) or not cwd):
            raise ProtocolError("eval cwd must be a non-empty string when present")
    elif kind == "shutdown":
        pass
    else:
        raise ProtocolError("unknown request type: %r" % (kind,))
    return request


def _handle_init(request, initialized):
    global _base_cwd
    if initialized:
        raise ProtocolError("duplicate init request")
    cwd = request["cwd"]
    try:
        os.chdir(cwd)
    except OSError:
        raise ProtocolError("init cwd is not accessible: %s" % cwd)
    _base_cwd = cwd
    _write_frame({"v": PROTOCOL_VERSION, "type": "ready", "pid": os.getpid()})


def _read_line(stdin):
    try:
        return stdin.readline()
    except (OSError, ValueError):
        return ""


def main():
    if _RUNNER_DIR not in sys.path:
        # Keep the staged lemon_tools importable after cells chdir elsewhere.
        sys.path.insert(0, _RUNNER_DIR)

    stdin = sys.stdin
    _install_input_rejection()
    _install_thread_cell_tags()
    _setup_descriptors()

    initialized = False
    while True:
        if stdin is None:
            # No request channel: the parent is gone, so leave quietly.
            _stop_pumps()
            return EXIT_OK
        line = _read_line(stdin)
        if line == "":
            # Parent EOF: nothing can be reported and nothing must be faked.
            _stop_pumps()
            return EXIT_OK
        line = line.strip()
        if not line:
            continue
        try:
            request = _parse_request(line)
            if request["type"] == "init":
                _handle_init(request, initialized)
                initialized = True
            elif request["type"] == "eval":
                if not initialized:
                    raise ProtocolError("eval before init")
                _run_cell(request)
            else:
                _write_frame({"v": PROTOCOL_VERSION, "type": "bye"})
                _stop_pumps()
                return EXIT_OK
        except ProtocolError as exc:
            _write_frame({"v": PROTOCOL_VERSION, "type": "fatal", "reason": str(exc)})
            _stop_pumps()
            return EXIT_FATAL


if __name__ == "__main__":
    sys.exit(main())
