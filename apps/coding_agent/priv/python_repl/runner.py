class _ClosedStdin:
    """A non-readable stdin stand-in: reading it is an explicit error."""

    encoding = "utf-8"
    errors = "replace"

    def readable(self):
        return False

    def writable(self):
        return False

    def seekable(self):
        return False

    def isatty(self):
        return False

    @property
    def closed(self):
        return False

    def close(self):
        pass

    def fileno(self):
        raise io.UnsupportedOperation("stdin is not available in the lemon python kernel")

    def read(self, *args):
        raise UnsupportedInput(_INPUT_ERROR)

    def readline(self, *args):
        raise UnsupportedInput(_INPUT_ERROR)

    def readlines(self, *args):
        raise UnsupportedInput(_INPUT_ERROR)

    def __iter__(self):
        return self

    def __next__(self):
        raise UnsupportedInput(_INPUT_ERROR)


def _reject_input(prompt=""):
    raise UnsupportedInput(
        _INPUT_ERROR if prompt == "" else "%s\n%s" % (_safe_str(prompt), _INPUT_ERROR)
    )


def _install_input_rejection():
    builtins.input = _reject_input
    sys.stdin = _ClosedStdin()
    sys.__stdin__ = sys.stdin


