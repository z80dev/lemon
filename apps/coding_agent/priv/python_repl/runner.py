def _configure_bridge(bridge, cell_id):
    if not isinstance(bridge, dict):
        raise RuntimeError("eval bridge must be an object with dir and token")
    directory = bridge.get("dir")
    token = bridge.get("token")
    if not isinstance(directory, str) or not directory:
        raise RuntimeError("eval bridge is missing its dir")
    if not isinstance(token, str) or not token:
        raise RuntimeError("eval bridge is missing its token")

    try:
        module = importlib.import_module("lemon_tools")
    except ImportError as exc:
        raise RuntimeError(
            "lemon_tools was not staged next to the runner; helper calls are unavailable"
        ) from exc

    # The shim rotates per-cell credentials (and, since per-cell budgets,
    # resets the text accumulator and counters). Older shims bake the rpc dir
    # in at render time and have nothing to configure; pass only the
    # arguments the staged shim accepts so either generation works.
    configure = getattr(module, "_configure", None)
    if configure is not None:
        _invoke_configure(configure, directory, token, bridge.get("max_text_bytes"), cell_id)

    _namespace["lemon_tools"] = module
    for name in HELPER_NAMES:
        if hasattr(module, name):
            _namespace[name] = getattr(module, name)


def _invoke_configure(configure, directory, token, budget, cell_id):
    try:
        arity = len(inspect.signature(configure).parameters)
    except (TypeError, ValueError):
        arity = 2

    args = [directory, token]
    if arity >= 3:
        args.append(budget if isinstance(budget, int) and budget > 0 else None)
    if arity >= 4:
        args.append(cell_id)
    configure(*args)


def _install_thread_cell_tags():
    """Make threads inherit the cell generation of the thread that created them.

    lemon_tools refuses bridge calls from threads tagged with an earlier
    cell (see `_live_bridge` in the shim), so a thread a finished cell left
    behind can neither spend a later cell's text budget nor write frames into
    its rpc directory.

    The tag is captured in `Thread.__init__` — at CONSTRUCTION time, in the
    creating thread — and children inherit their creator's generation. A
    start-time stamp could be bypassed: a stale cell-1 thread can wait for
    cell 2 and then spawn, and the spawn would be stamped with cell 2 (the
    *current* cell) rather than the stale thread that caused it. With
    construction-time inheritance, a stale thread's descendants carry the
    stale generation forever and are refused by the bridge.

    The main thread (and any thread without a tag, e.g. ones this runner
    starts outside any cell) has no generation, so its children fall back to
    the currently open cell — exactly the behavior runner-internal threads
    always had.
    """
    if getattr(threading.Thread.__init__, "_lemon_tagged", False):
        return

    original_init = threading.Thread.__init__

    def __init__(self, *args, **kwargs):
        inherited = getattr(threading.current_thread(), "_lemon_gen", None)
        original_init(self, *args, **kwargs)
        self._lemon_gen = (
            inherited if inherited is not None else _current_cell()
        )

    __init__._lemon_tagged = True
    threading.Thread.__init__ = __init__


def _prepare_cell(cwd, bridge, cell_id):
    try:
        os.chdir(cwd)
    except OSError as exc:
        raise RuntimeError(
            "cell cwd is no longer accessible: %s (%s)" % (cwd, exc.strerror or exc)
        ) from exc
    if bridge is not None:
        _configure_bridge(bridge, cell_id)


def _run_cell(request):
    cell_id = request["id"]
    cwd = request.get("cwd") or _base_cwd
    try:
        # `started` marks the no-retry boundary: from here the host must
        # never replay or fall back for this cell.
        _write_frame({"v": PROTOCOL_VERSION, "type": "started", "id": cell_id})
        # Stream frames may only follow `started`, never precede it.
        _set_open_cell(cell_id)
        try:
            code = compile(request["code"], CELL_FILENAME, "exec")
            _prepare_cell(cwd, request.get("bridge"), cell_id)
            exec(code, _namespace)
        except BaseException as exc:  # noqa: BLE001 - the kernel must survive cells
            _emit_exception(cell_id, exc)
        # Success or failure, the cell's streams are quiesced and exactly one
        # `done` closes it. Attribution is removed first so output from a
        # late user thread cannot be emitted after the terminal frame.
        _quiesce()
        _close_cell_and_emit_done(cell_id)
    finally:
        _set_open_cell(None)


