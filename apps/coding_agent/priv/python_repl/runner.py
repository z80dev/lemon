# capture pipes
# ---------------------------------------------------------------------------


class _Drainer(threading.Thread):
    """Pumps one capture pipe to stream frames while cell code runs.

    Draining concurrently matters: a child process inheriting fd 1/2 writing
    more than the pipe buffer would otherwise deadlock against its waiting
    parent.
    """

    def __init__(self, fd, stream_name):
        super().__init__(daemon=True, name="lemon-drain-" + stream_name)
        self.fd = fd
        self.stream_name = stream_name
        self.last_data = 0.0
        # Set whenever a poll observed the pipe empty, cleared on every read;
        # quiescing waits for "empty was observed after the last byte".
        self.quiet_since = time.monotonic()
        self.stopping = threading.Event()

    def run(self):
        if os.name == "posix":
            self._run_select()
        else:
            # select() does not accept pipes on Windows; fall back to
            # blocking reads (quiesce there is a bounded wait instead of a
            # quiet-window check).
            self._run_blocking()

    def _run_select(self):
        while not self.stopping.is_set():
            try:
                readable, _, _ = select.select([self.fd], [], [], 0.01)
            except (OSError, ValueError):
                return
            if self.fd in readable:
                if not self._read_and_emit():
                    return
            else:
                self.quiet_since = time.monotonic()

    def _run_blocking(self):
        while not self.stopping.is_set():
            if not self._read_and_emit():
                return

    def _read_and_emit(self):
        try:
            data = os.read(self.fd, STREAM_CHUNK)
        except (OSError, ValueError):
            return False
        if not data:
            # The write end only closes at process teardown; an early EOF
            # means the pipe is unusable.
            return False
        self.last_data = time.monotonic()
        self.quiet_since = None
        cell_id = _begin_stream_write()
        if cell_id is None:
            return True
        try:
            _emit_stream(cell_id, self.stream_name, data)
        finally:
            _end_stream_write()
        return True


def _setup_descriptors():
    global _control_fd
    try:
        os.setsid()
    except (AttributeError, OSError):
        # Already a group leader (or unsupported platform): the parent still
        # terminates the whole tree on teardown.
        pass

    _control_fd = os.dup(1)
    for fd in (_control_fd, 0):
        # The control channel and the request channel must not leak into
        # descendants: children inheriting them could forge or steal frames.
        try:
            os.set_inheritable(fd, False)
        except (AttributeError, OSError):
            pass

    out_r, out_w = os.pipe()
    err_r, err_w = os.pipe()
    for fd in (out_r, err_r):
        # Read ends stay process-private; fd 1/2 (dup2'd below) keep their
        # inheritable flag so user child processes keep writing captured
        # output.
        try:
            os.set_inheritable(fd, False)
        except (AttributeError, OSError):
            pass
    os.dup2(out_w, 1)
    os.dup2(err_w, 2)
    os.close(out_w)
    os.close(err_w)

    _drainers.extend([_Drainer(out_r, "stdout"), _Drainer(err_r, "stderr")])
    for drainer in _drainers:
        drainer.start()


def _flush_python_streams():
    for stream in (sys.stdout, sys.stderr):
        try:
            stream.flush()
        except Exception:
            pass


def _quiesce():
    """Wait, for a bounded interval, for in-flight stream writes to finish.

    All platforms wait for writes already claimed by a drainer. POSIX adds a
    post-flush empty-pipe observation; Windows cannot select pipes, so its
    blocking drainers have no equivalent quiet signal. The later close gate
    still drops any bytes a lingering thread writes after this bound.
    """
    _flush_python_streams()
    for drainer in _drainers:
        drainer.quiet_since = None

    deadline = time.monotonic() + MAX_QUIESCE_SECONDS
    while True:
        with _inflight_lock:
            writes_drained = _inflight_writes == 0

        if os.name == "posix":
            settled = writes_drained and all(
                drainer.quiet_since is not None and drainer.quiet_since > drainer.last_data
                for drainer in _drainers
            )
        else:
            settled = writes_drained

        if settled or time.monotonic() >= deadline:
            return
        time.sleep(0.002)



def _detach_user_streams():
    """Point fd 1/2 at devnull so interpreter-exit flushes cannot block."""
    try:
        devnull = os.open(os.devnull, os.O_WRONLY)
        os.dup2(devnull, 1)
        os.dup2(devnull, 2)
        if devnull > 2:
            os.close(devnull)
    except OSError:
        pass


def _stop_pumps():
    for drainer in _drainers:
        drainer.stopping.set()
    _detach_user_streams()


