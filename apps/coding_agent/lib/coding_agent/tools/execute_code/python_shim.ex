defmodule CodingAgent.Tools.ExecuteCode.PythonShim do
  @moduledoc """
  Renders the stdlib-only python shim (`lemon_tools.py`) a script imports to
  reach the Lemon tool layer, plus the one-line import prelude prepended to
  the submitted script.

  Pure functions — no I/O — so the generated text is fully testable and, given
  the same configuration and tool list, byte-identical between runs.

  The shim speaks the file-RPC protocol: a request is written to
  `req-<id>.json.tmp` and atomically `os.replace`d onto `req-<id>.json`; the
  response appears the same way at `res-<id>.json`. Every request carries the
  per-cell bearer token configured by `_configure/2`. Only `json`, `os`,
  `threading`, `time`, and `concurrent.futures` are used, so the shim works on
  any stock python3.

    * `text(s)` — the result channel. Each call atomically flushes a numbered
      `text-<n>.json` block into the rpc dir (write-through, never at exit, so
      blocks survive a timeout or kill) under a shared lock, within a byte
      budget; the *encoded frame* — exactly the bytes `json.dump` writes to
      disk, JSON escaping included — is what the budget charges, so a
      NUL-heavy string that quadruples under escaping is refused by the same
      budget the host enforces on the file. An over-budget call raises
      `ToolError` and leaves the previously flushed blocks intact.
    * `notify(msg)` — the streaming side channel. Fire-and-forget numbered
      `notify-<n>.json` frames; the Elixir pump consumes and forwards them as
      partial updates, never as responses.
    * `batch(calls)` — parallel helper calls through a bounded
      `ThreadPoolExecutor`, each worker running the plain blocking `_call`.
      All calls are waited out before any error is re-raised, so a mixed
      batch never tears its side effects.

  ## Per-cell bridge isolation

  All authority lives in one immutable-per-cell `_Bridge` object (rpc dir,
  token, text budget, generation, and the per-cell sequence counters and
  text accumulator). `_configure/4` installs a fresh bridge — so a new cell
  always starts with clean counters and a full budget, no matter what
  earlier cells consumed — and every helper captures the current bridge once
  at entry. The persistent runner stamps each started thread with the cell
  that started it; a thread from an earlier cell is refused (`ToolError`)
  rather than let it spend or write into a later cell's bridge. This is
  isolation hygiene, not a sandbox: a genuinely hostile script can always
  write raw protocol files itself.
  """

  alias CodingAgent.Tools.ExecuteCode.Config

  # Fixed emission order, independent of how config lists the tools, so the
  # generated prelude stays deterministic.
  @stub_order ~w(read grep find ls webfetch)

  # Must match `Config`'s `@default_max_text_bytes`; both are pinned by tests.
  @default_text_budget 65_536

  # Cap on the ThreadPoolExecutor used by batch(): any higher fan-out just
  # queues python-side, because the Elixir pump bounds real dispatch
  # concurrency at `max_parallel_rpc`.
  @batch_max_workers 16

  @doc """
  Render an unconfigured, authority-free `lemon_tools.py` module defining a
  stub per enabled tool, the `text()`/`notify()` result channels, and
  `batch()` for parallel helper calls.

  Persistent Python sessions stage this source once and rotate its bridge
  per cell with `_configure/4`, which resets the per-cell counters and
  installs the caller's `max_text_bytes` budget. The budget baked here is
  the fallback for `_configure` calls that omit one, so a live kernel keeps
  the budget it was first staged with until it is reset or reaped.
  """
  @spec render_module(tools :: [String.t()], max_text_bytes :: pos_integer()) :: String.t()
  def render_module(tools, max_text_bytes \\ @default_text_budget)
      when is_list(tools) and is_integer(max_text_bytes) and max_text_bytes > 0 do
    enabled = enabled_tools(tools)

    header = """
    # Generated by Lemon execute_code. Do not edit.
    import json, os, threading, time
    from concurrent.futures import ThreadPoolExecutor

    _DEFAULT_TEXT_BUDGET = #{max_text_bytes}
    _POLL_S = 0.02
    _BATCH_MAX_WORKERS = #{@batch_max_workers}
    _LOCK = threading.Lock()
    _BRIDGE = None


    class _Bridge:
        # One cell's complete bridge state: where to write, with what
        # authority, under which text budget, and with which sequence
        # counters. Immutable credentials, mutable counters that only the
        # owning cell's calls touch — nothing leaks between cells.
        __slots__ = (
            "dir",
            "token",
            "budget",
            "gen",
            "seq",
            "text_seq",
            "notify_seq",
            "text_bytes",
        )

        def __init__(self, rpc_dir, token, budget, gen):
            self.dir = rpc_dir
            self.token = token
            self.budget = budget
            self.gen = gen
            self.seq = 0
            self.text_seq = 0
            self.notify_seq = 0
            self.text_bytes = 0


    def _configure(rpc_dir, token, budget=None, generation=None):
        # Per-cell reset: every configure installs a brand-new bridge, so the
        # sequence counters and the text budget start fresh no matter what
        # earlier cells (or threads they left behind) consumed.
        global _BRIDGE
        with _LOCK:
            cap = (
                budget
                if isinstance(budget, int) and budget > 0
                else _DEFAULT_TEXT_BUDGET
            )
            _BRIDGE = _Bridge(rpc_dir, token, cap, generation)


    def _live_bridge():
        # One capture of the current bridge, used consistently for the whole
        # call. A thread started in an earlier cell is stamped with that
        # cell's generation by the persistent runner and is refused here: its
        # writes can never land in — and its bytes can never come out of — a
        # cell it was not part of. (The stamp only exists in persistent
        # kernels; per-call processes never configure a second bridge.)
        with _LOCK:
            bridge = _BRIDGE
        if bridge is None:
            raise ToolError("lemon_tools is not configured for this cell")
        tag = getattr(threading.current_thread(), "_lemon_gen", None)
        if tag is not None and tag != bridge.gen:
            raise ToolError("lemon_tools bridge belongs to a finished cell")
        return bridge


    class ToolError(Exception):
        pass


    def _atomic_write(rpc_dir, final_name, payload):
        # Same publication discipline as every protocol file: an O_EXCL tmp at
        # 0600, verified owner-only, renamed into place so a reader never sees
        # a half-written frame and a planted symlink is replaced, not followed.
        tmp = os.path.join(rpc_dir, final_name + ".tmp")
        final = os.path.join(rpc_dir, final_name)
        flags = os.O_WRONLY | os.O_CREAT | os.O_EXCL | getattr(os, "O_NOFOLLOW", 0)
        try:
            fd = os.open(tmp, flags, 0o600)
        except FileExistsError:
            raise ToolError("rpc temp for %s already exists" % final_name)
        if (os.fstat(fd).st_mode & 0o777) != 0o600:
            os.close(fd)
            os.unlink(tmp)
            raise ToolError("rpc temp for %s is not owner-only" % final_name)
        try:
            with os.fdopen(fd, "w", encoding="utf-8") as f:
                json.dump(payload, f)
        except BaseException:
            try:
                os.unlink(tmp)
            except OSError:
                pass
            raise
        os.replace(tmp, final)


    def text(s):
        # Result channel: each block is flushed to disk as it is written
        # (never at exit), so everything emitted before a timeout or kill
        # still reaches the tool result. Numbering and the byte budget are
        # lock-guarded because batch() workers call this from many threads.
        if s is None:
            s = ""
        elif not isinstance(s, str):
            s = str(s)
        bridge = _live_bridge()
        with _LOCK:
            seq = bridge.text_seq + 1
            frame = {"n": seq, "text": s}
            # Charge the encoded frame — exactly the bytes json.dump writes
            # to disk — so the script-side budget and the host-side size
            # check always agree, whatever JSON escaping expands the text to.
            encoded = len(json.dumps(frame))
            if bridge.text_bytes + encoded > bridge.budget:
                raise ToolError(
                    "text() byte budget exceeded (%d bytes accumulated, %d more requested, cap %d)"
                    % (bridge.text_bytes, encoded, bridge.budget)
                )
            bridge.text_seq = seq
            bridge.text_bytes += encoded
        _atomic_write(bridge.dir, "text-%d.json" % seq, frame)


    def notify(msg):
        # Streaming side channel: fire-and-forget, never blocks for a reply.
        if msg is None:
            msg = ""
        elif not isinstance(msg, str):
            msg = str(msg)
        bridge = _live_bridge()
        with _LOCK:
            bridge.notify_seq += 1
            seq = bridge.notify_seq
        _atomic_write(bridge.dir, "notify-%d.json" % seq, {"n": seq, "msg": msg})


    def batch(calls):
        # Parallel helper calls: each worker runs the plain blocking _call, so
        # ids stay unique (the counter is lock-guarded) and a failure surfaces
        # as the same ToolError a plain call raises. Every call is waited out
        # before any exception is re-raised, so side effects are never torn.
        calls = list(calls)
        if not calls:
            return []
        workers = min(len(calls), _BATCH_MAX_WORKERS)
        with ThreadPoolExecutor(max_workers=workers) as pool:
            futures = [pool.submit(_call, tool, params or {}) for tool, params in calls]
            results = []
            first_error = None
            for future in futures:
                try:
                    results.append(future.result())
                except BaseException as exc:
                    results.append(None)
                    if first_error is None:
                        first_error = exc
        if first_error is not None:
            raise first_error
        return results


    def _call(tool, params):
        bridge = _live_bridge()
        with _LOCK:
            bridge.seq += 1
            req_id = bridge.seq
        params = {k: v for k, v in params.items() if v is not None}
        _atomic_write(
            bridge.dir,
            "req-%d.json" % req_id,
            {"id": req_id, "token": bridge.token, "tool": tool, "params": params},
        )
        res_path = os.path.join(bridge.dir, "res-%d.json" % req_id)
        while True:
            if os.path.exists(res_path):
                with open(res_path) as f:
                    res = json.load(f)
                if res.get("ok"):
                    return res.get("content", "")
                raise ToolError(res.get("error") or "tool call failed")
            time.sleep(_POLL_S)
    """

    Enum.reduce(enabled, header, fn name, acc -> acc <> "\n\n" <> stub(name) end)
  end

  @doc """
  Render an unconfigured `lemon_tools.py` with the default text budget.

  Kept for the one-shot compatibility path; persistent callers should use
  `render_module/2` to make the absence of initial bridge authority and the
  baked budget explicit.
  """
  @spec render_prelude(tools :: [String.t()]) :: String.t()
  def render_prelude(tools) when is_list(tools), do: render_module(tools)

  @doc """
  Render `lemon_tools.py` preconfigured for a one-shot `execute_code` run.

  `max_text_bytes` defaults to #{@default_text_budget} and is installed as
  the one bridge's `text()` budget (the module default and the configure
  call agree, so there is exactly one source of truth on disk).
  """
  @spec render_prelude(
          rpc_dir :: String.t(),
          token :: String.t(),
          tools :: [String.t()],
          max_text_bytes :: pos_integer()
        ) :: String.t()
  def render_prelude(rpc_dir, token, tools, max_text_bytes \\ @default_text_budget)
      when is_binary(rpc_dir) and is_binary(token) and is_list(tools) do
    render_module(tools, max_text_bytes) <>
      "\n\n_configure(#{Jason.encode!(rpc_dir)}, #{Jason.encode!(token)}, #{max_text_bytes})\n"
  end

  @doc """
  The single import line prepended to the submitted script.
  """
  @spec import_line(tools :: [String.t()]) :: String.t()
  def import_line(tools \\ Config.allowlist()) when is_list(tools) do
    # The result-channel helpers are part of the module itself, not the
    # tool-gated stubs, so they import even when `tools` narrows to none.
    names = ["ToolError" | enabled_tools(tools)] ++ ~w(text notify batch)
    "from lemon_tools import " <> Enum.join(names, ", ")
  end

  @doc """
  Prepend the import line to the user script.

  Exactly one line is injected, so python traceback line numbers are offset by
  one — the tool description says so.
  """
  @spec render_script(user_script :: String.t(), tools :: [String.t()]) :: String.t()
  def render_script(user_script, tools \\ Config.allowlist()) when is_binary(user_script) do
    import_line(tools) <> "\n" <> user_script
  end

  defp enabled_tools(tools), do: Enum.filter(@stub_order, &(&1 in tools))

  defp stub("read") do
    """
    def read(path, offset=None, limit=None):
        return _call("read", {"path": path, "offset": offset, "limit": limit})
    """
    |> String.trim_trailing()
  end

  defp stub("grep") do
    """
    def grep(pattern, path=None, glob=None, case_sensitive=None, literal=None, context_lines=None, max_results=None):
        return _call("grep", {"pattern": pattern, "path": path, "glob": glob, "case_sensitive": case_sensitive, "literal": literal, "context_lines": context_lines, "max_results": max_results})
    """
    |> String.trim_trailing()
  end

  defp stub("find") do
    """
    def find(pattern, path=None, type=None, max_depth=None, max_results=None, hidden=None):
        return _call("find", {"pattern": pattern, "path": path, "type": type, "max_depth": max_depth, "max_results": max_results, "hidden": hidden})
    """
    |> String.trim_trailing()
  end

  defp stub("ls") do
    """
    def ls(path=None, all=None, long=None, recursive=None, max_depth=None, max_entries=None):
        return _call("ls", {"path": path, "all": all, "long": long, "recursive": recursive, "max_depth": max_depth, "max_entries": max_entries})
    """
    |> String.trim_trailing()
  end

  defp stub("webfetch") do
    """
    def webfetch(url, extract_mode=None, max_chars=None):
        return _call("webfetch", {"url": url, "extractMode": extract_mode, "maxChars": max_chars})
    """
    |> String.trim_trailing()
  end
end
